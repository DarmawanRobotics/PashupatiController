String tr(String language, String key, [Map<String, Object> args = const {}]) {
  var text = (language == 'id' ? _id[key] : null) ?? _en[key] ?? key;
  args.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
  return text;
}

