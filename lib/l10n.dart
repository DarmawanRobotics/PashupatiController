/// Label of an inspection category; an unknown one reads as its name.
String categoryLabel(String language, String category) {
  final key = 'cat_$category';
  final label = tr(language, key);
  return label == key ? category.replaceAll('_', ' ') : label;
}

String tr(String language, String key, [Map<String, Object> args = const {}]) {
  var text = (language == 'id' ? _id[key] : null) ?? _en[key] ?? key;
  args.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
  return text;
}

